#!/usr/bin/env node
// scripts/revert-bulk-flagged.mjs
//
// Per Philip's directive 2026-07-27: if a row needs admin review,
// it does NOT belong in the manifest. Remove every row created by
// the bulk-processor (they all flagged missing MASTER AI PROMPT).
// Keep only rows authored with real MASTER DESCRIPTIONs.

import { promises as fs } from "node:fs";
import path from "node:path";

const MANIFEST = path.join(process.cwd(), "data", "nex-image-manifest.json");

const raw = await fs.readFile(MANIFEST, "utf8");
const manifest = JSON.parse(raw);

const before = Object.keys(manifest.images ?? {}).length;
const kept = {};
let removed = 0;

for (const [url, row] of Object.entries(manifest.images ?? {})) {
  const isAutoGenerated =
    row.created_by === "bulk-processor" || row.created_by === "pipeline";
  if (isAutoGenerated) {
    removed++;
    continue;
  }
  kept[url] = row;
}

manifest.images = kept;
manifest.generated_at = new Date().toISOString();

await fs.writeFile(MANIFEST, JSON.stringify(manifest, null, 2), "utf8");

console.log("Manifest revert complete.");
console.log(`  Before: ${before} rows`);
console.log(`  Removed: ${removed} bulk-processed rows (all needed admin review)`);
console.log(`  After: ${Object.keys(kept).length} rows (authored only)`);
