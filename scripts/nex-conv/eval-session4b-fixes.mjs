// scripts/nex-conv/eval-session4b-fixes.mjs
//
// Regression test for the two Session 4b bugs (Philip 2026-08-20):
//
//   Bug 1 · Correction direction
//     Customer: "Actually, change the oak to walnut."
//     Prior state: material_primary=oak
//     Correct outcome: material_primary=walnut, corrections_log records
//                      oak→walnut, and the customer-facing reply refers
//                      to walnut (not oak).
//     Prior bug:    state kept oak (correction loop iterated both
//                   materials and last-write-wins).
//
//   Bug 2 · Balustrade extraction
//     Customer: "Add glass balustrades to the design."
//     Correct outcome: established_facts.balustrade = { value: 'glass', ... }
//                      and material_primary is UNCHANGED.
//     Prior bug:    plural "balustrades" not aliased → 'balustrade'
//                   entity never extracted → no writer path in state.mjs.
//
// USAGE
//   npx tsx scripts/nex-conv/eval-session4b-fixes.mjs
//
// EXIT CODES
//   0 · both tests pass
//   2 · at least one test fails
//   1 · runner exception
//
// GUARDRAILS
//   · Uses JsonlStore (no Postgres · no dev server needed).
//   · Uses the exact same functions the /api/nex-conv/chat route handler
//     calls in production (infer.processTurn + updateStateFromCustomer).
//   · Fresh conversation_id per test · doesn't pollute prior data.
//   · Prose is generated by the local Qwen 2.5 3B via Ollama —
//     ensures the reply-vs-state agreement check runs against the same
//     model users would see. If Ollama is down, the prose check
//     degrades to "state-only" and the runner reports that clearly.

import { createStore } from "./lib/store-factory.mjs";
import { STAIRCASE_ENTITIES, STAIRCASE_INTENTS } from "./lib/entities.mjs";
import * as infer from "./lib/infer.mjs";
import { randomUUID } from "node:crypto";

// ─── Test helpers ─────────────────────────────────────────────────

async function boot() {
  const store = await createStore({ backend: "jsonl" });
  for (const intent of STAIRCASE_INTENTS) await store.upsertIntent(intent);
  for (const ent of STAIRCASE_ENTITIES) await store.upsertEntity({ ...ent, brain: "staircase_brain" });
  return store;
}

async function turn(store, state, text, opts = {}) {
  const out = await infer.processTurn({
    store,
    state,
    brain: "staircase_brain",
    text,
    speaker: "customer",
    withProse: opts.withProse ?? true,
  });
  try { await store.upsertState(state); } catch { /* non-fatal */ }
  return out;
}

// ─── Bug 1 · Correction direction ────────────────────────────────

async function testCorrectionDirection(store) {
  const t = { name: "BUG_1_correction_direction", assertions: [], errors: [] };

  const conversationId = randomUUID();
  const state = infer.newState({ conversation_id: conversationId, brain: "staircase_brain", business_id: "session4b-regression" });

  // Turn 1: seed material_primary=oak via a direct specify.
  await turn(store, state, "I want an oak staircase.", { withProse: false });
  const seededOak = state.established_facts.material_primary?.value === "oak";
  t.assertions.push(assert(seededOak, "setup", "material_primary=oak after 'I want an oak staircase.'", {
    material_primary: state.established_facts.material_primary,
  }));

  // Turn 2: the exact correction phrasing that failed in the live test.
  const out2 = await turn(store, state, "Actually, change the oak to walnut.", { withProse: true });

  const finalMaterial = state.established_facts.material_primary?.value;
  t.assertions.push(assert(
    finalMaterial === "walnut",
    "state",
    `material_primary should be 'walnut' after correction · got '${finalMaterial}'`,
    { material_primary: state.established_facts.material_primary },
  ));

  const correction = state.corrections_log.find(
    (c) => c.field === "material_primary" && c.previous === "oak" && c.new === "walnut",
  );
  t.assertions.push(assert(
    !!correction,
    "audit",
    "corrections_log should contain { field: material_primary, previous: oak, new: walnut }",
    { corrections_log: state.corrections_log },
  ));

  // Reply-vs-state agreement · verifies the customer-facing prose matches
  // the persisted state. If Ollama is down, downgrade to a soft-warn.
  const reply = out2.prose?.text ?? "";
  const proseErr = out2.prose?.error;
  if (proseErr) {
    t.assertions.push(warn("prose", `prose skipped · ${String(proseErr).slice(0, 200)}`));
  } else {
    const mentionsWalnut = /\bwalnut\b/i.test(reply);
    t.assertions.push(assert(
      mentionsWalnut,
      "reply",
      "customer-facing reply should mention 'walnut' after the correction (reply-vs-state agreement)",
      { reply: reply.slice(0, 300) },
    ));
    // Weak reverse check: if the reply says "walnut to oak" or "oak instead
    // of walnut" or similar direction-reversed phrasing, flag it. This is
    // heuristic — treats false positives as warnings, not failures.
    const reversedPhrasing = /\bfrom\s+walnut\s+(back\s+)?to\s+oak\b|\boak\s+(instead|rather than)\s+walnut\b/i.test(reply);
    if (reversedPhrasing) {
      t.assertions.push(warn("reply", "reply appears to reverse the correction direction · flagged as warning · verify by eye", { reply: reply.slice(0, 300) }));
    }
  }

  return t;
}

// ─── Bug 2 · Balustrade extraction ───────────────────────────────

async function testBalustradeExtraction(store) {
  const t = { name: "BUG_2_balustrade_extraction", assertions: [], errors: [] };

  const conversationId = randomUUID();
  const state = infer.newState({ conversation_id: conversationId, brain: "staircase_brain", business_id: "session4b-regression" });

  // Seed with an oak staircase so we can verify balustrade is separate
  // from material_primary (must NOT overwrite oak with glass).
  await turn(store, state, "I want an oak staircase.", { withProse: false });
  const seededOak = state.established_facts.material_primary?.value === "oak";
  t.assertions.push(assert(seededOak, "setup", "material_primary=oak after 'I want an oak staircase.'", {
    material_primary: state.established_facts.material_primary,
  }));

  // The exact phrasing that failed in the live test.
  const out2 = await turn(store, state, "Add glass balustrades to the design.", { withProse: true });

  const balustradeFact = state.established_facts.balustrade;
  t.assertions.push(assert(
    balustradeFact?.value === "glass",
    "state",
    `established_facts.balustrade.value should be 'glass' · got '${balustradeFact?.value ?? "(undefined)"}'`,
    { balustrade: balustradeFact },
  ));

  const materialStillOak = state.established_facts.material_primary?.value === "oak";
  t.assertions.push(assert(
    materialStillOak,
    "state",
    `material_primary should remain 'oak' after balustrade addition · got '${state.established_facts.material_primary?.value}'`,
    { material_primary: state.established_facts.material_primary },
  ));

  // Verify balustrade entity was extracted (Bug 2a fix: plural alias).
  const entitiesExtracted = out2.understood_entities ?? [];
  const balustradeEntityPresent = entitiesExtracted.some((e) => (e.slug ?? e) === "balustrade");
  t.assertions.push(assert(
    balustradeEntityPresent,
    "extraction",
    "extractor should recognise 'balustrades' (plural) as the balustrade entity",
    { understood_entities: entitiesExtracted },
  ));

  const proseErr = out2.prose?.error;
  if (proseErr) {
    t.assertions.push(warn("prose", `prose skipped · ${String(proseErr).slice(0, 200)}`));
  }

  return t;
}

// ─── Runner infrastructure ────────────────────────────────────────

function assert(condition, kind, description, evidence) {
  return { kind, description, passed: !!condition, evidence, level: condition ? "pass" : "fail" };
}

function warn(kind, description, evidence) {
  return { kind, description, passed: true, evidence, level: "warn" };
}

function printTest(t) {
  const anyFail = t.assertions.some((a) => a.level === "fail");
  const status = anyFail ? "FAIL ✗" : "PASS ✓";
  console.log("");
  console.log(`─── ${t.name} · ${status} ───`);
  for (const a of t.assertions) {
    const marker = a.level === "fail" ? "✗" : a.level === "warn" ? "⚠" : "✓";
    console.log(`  ${marker} [${a.kind}] ${a.description}`);
    if (a.evidence && (a.level === "fail" || a.level === "warn")) {
      console.log(`      evidence: ${JSON.stringify(a.evidence).slice(0, 400)}`);
    }
  }
  return !anyFail;
}

async function main() {
  console.log("═══════════════════════════════════════════════════════════");
  console.log("SESSION 4b · Regression tests for correction + balustrade");
  console.log("═══════════════════════════════════════════════════════════");
  const t0 = Date.now();
  const store = await boot();
  console.log(`[boot] store ready · knowledge_items=${store.mem.knowledge_items.size} · entities=${store.mem.entities.size} · intents=${store.mem.intents.size}`);

  const results = [];
  results.push(await testCorrectionDirection(store));
  results.push(await testBalustradeExtraction(store));

  const passes = results.map(printTest);

  console.log("");
  console.log("═══════════════════════════════════════════════════════════");
  console.log("SUMMARY");
  console.log("═══════════════════════════════════════════════════════════");
  const passed = passes.filter(Boolean).length;
  console.log(`passed: ${passed}/${results.length}`);
  console.log(`failed: ${results.length - passed}/${results.length}`);
  console.log(`elapsed: ${((Date.now() - t0) / 1000).toFixed(1)}s`);

  process.exit(passed === results.length ? 0 : 2);
}

main().catch((e) => {
  console.error("UNHANDLED:", e instanceof Error ? e.stack ?? e.message : String(e));
  process.exit(1);
});
