/* ══════════════════════════════════════════════════════════════════
   MESSAGE BUBBLES · Summit · NEX · Customer · distinct visual language
   ══════════════════════════════════════════════════════════════════ */

function MessageBubble({ msg, brandInitial, index }: { msg: Msg; brandInitial: string; index: number }) {
  if (msg.agent === "customer") {
    return (
      <div className="mt1-bubble-in" style={{ display: "flex", justifyContent: "flex-end" }}>
        <div
          style={{
            background: T.color.accent,
            color: "#FFFFFF",
            borderRadius: 18,
            borderBottomRightRadius: 4,
            padding: "12px 16px",
            fontSize: 14.5,
            lineHeight: 1.5,
            maxWidth: "78%",
            whiteSpace: "pre-wrap",
            boxShadow: "0 8px 20px -14px rgba(181, 143, 94, 0.6)"
          }}
        >
          {msg.text}
        </div>
      </div>
    );
  }

  // NEX + Summit share the "left bubble" pattern but with distinct
  // avatar treatments so the customer can tell who's speaking.
  const isNex = msg.agent === "nex";
  return (
    <div className="mt1-bubble-in" style={{ display: "flex", gap: 10, alignItems: "flex-end" }}>
      <AgentAvatar agent={msg.agent} brandInitial={brandInitial} />
      <div style={{ display: "flex", flexDirection: "column", gap: 4, maxWidth: "78%" }}>
        {isNex && (
          <div style={{ fontSize: 10, letterSpacing: "0.18em", textTransform: "uppercase", color: "#C6906F", fontWeight: 700, marginLeft: 2 }}>
            Nex · Assistant
          </div>
        )}
        <div
          style={{
            background: T.color.surfaceCard,
            border: `1px solid ${isNex ? "rgba(198, 144, 111, 0.28)" : T.color.hairline}`,
            borderRadius: 18,
            borderBottomLeftRadius: 4,
            padding: "12px 16px",
            fontSize: 14.5,
            lineHeight: 1.55,
            color: T.color.ink,
            whiteSpace: "pre-wrap",
            boxShadow: "0 2px 8px -4px rgba(58, 52, 40, 0.06)"
          }}
        >
          {msg.text}
        </div>
      </div>
    </div>
  );
}

function AgentAvatar({ agent, brandInitial }: { agent: Agent; brandInitial: string }) {
  if (agent === "nex") {
    // NEX · orange · "Nex" text (Philip 2026-08-15) · clearly a
    // system helper, distinct from Summit's tan brand mark.
    return (
      <div
        aria-hidden
        style={{
          width: 30, height: 30, flexShrink: 0,
          borderRadius: "50%",
          background: "#C6906F",
          color: "#FFFFFF",
          display: "flex", alignItems: "center", justifyContent: "center",
          fontFamily: T.font.sans, fontSize: 11, fontWeight: 700, letterSpacing: "-0.01em"
        }}
      >
        Nex
      </div>
    );
  }
  // Summit · warm tan, serif "S", concierge feel
  return (
    <div
      aria-hidden
      style={{
        width: 28, height: 28, flexShrink: 0,
        borderRadius: "50%",
        background: T.color.accent,
        color: "#FFFFFF",
        display: "flex", alignItems: "center", justifyContent: "center",
        fontFamily: T.font.serif, fontSize: 14, fontWeight: 500
      }}
    >
      {brandInitial}
    </div>
  );
}

