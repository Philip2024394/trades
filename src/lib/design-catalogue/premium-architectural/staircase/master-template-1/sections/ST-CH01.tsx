function ThinkDot({ delay }: { delay: number }) {
  return (
    <span
      aria-hidden
      style={{
        width: 6, height: 6, borderRadius: "50%",
        background: T.color.inkFaint,
        animation: `mt1-think-bob 1.2s ease-in-out ${delay}s infinite`
      }}
    />
  );
}

