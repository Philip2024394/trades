// NEX Design Catalogue · ST-CH01 · Branded Customer Chat (v2)
// (Philip 2026-08-15 · full rebuild for the world-class UX pass).
//
// The customer opened Summit's chat window. This surface must feel
// like Summit greeted them, not like a template. No NEX chrome from
// the outer product; instead a dual-agent flow inside:
//   · Summit    · the human business (tan "S" serif mark)
//   · NEX       · Summit's assistant (small olive "N" — clearly labelled)
//   · Customer  · tan-filled bubbles on the right
//
// Alive-details in this v2:
//   1. Typing indicator arrives BEFORE Summit's greeting (700ms)
//   2. Greeting rotates from a per-time-of-day pool
//   3. Bubbles slide + fade in with a spring
//   4. Presence dot slow-pulses
//   5. First customer message triggers NEX to introduce herself
//      (~1200ms after send) and set expectations honestly
//   6. Placeholder in the composer morphs through prompts
//   7. Send button subtle hover glow + tap scale
//   8. Fresh warm-frosted glass on floating header + composer
//      (Philip 2026-08-15 · "not shaded")

"use client";

import { useCallback, useEffect, useMemo, useRef, useState } from "react";
import { MT1_TOKENS as T } from "../tokens";

type Agent = "summit" | "nex" | "customer";
type Msg = { agent: Agent; text: string };

type Config = {
  brandName?: string;
  brandInitial?: string;
  presence?: "online" | "away";
  presenceCaption?: string;
  suggestedPrompts?: string[];
  initialConversation?: Msg[];
  /** If true, skip the auto-greeting flow (useful for testing empty state). */
  skipGreeting?: boolean;
  /**
   * Chat wallpaper (Philip 2026-08-15). Owner-swappable later via
   * NEX Assist ("change my chat wallpaper"). Default is Summit's
   * Premium Architectural wallpaper on ImageKit.
   */
  chatBackgroundUrl?: string;
};

const DEFAULTS: Required<Config> = {
  brandName:       "Summit",
  brandInitial:    "S",
  presence:        "online",
  presenceCaption: "Typically replies within an hour",
  suggestedPrompts: [
    "I want a floating oak staircase — how much roughly?",
    "Do you install in my area?",
    "Can I see examples of your work?",
    "How long does a staircase project take?"
  ],
  initialConversation: [],
  skipGreeting: false,
  chatBackgroundUrl: "https://ik.imagekit.io/5vv5pw26q/ChatGPT%20Image%20Aug%2015,%202026,%2001_05_08%20AM.png"
};

/* Time-of-day welcome pool · rotates on every mount so no visitor
 * sees the same greeting twice in a row. */
const GREETINGS = {
  morning: [
    "Good morning — welcome to Summit. What's on your mind about your staircase today?",
    "Morning. Great to have you. Are you exploring designs, or ready for a quote?",
    "Hello and good morning. Tell us a little about your project."
  ],
  afternoon: [
    "Good afternoon. Thanks for stopping by — how can we help with your staircase?",
    "Afternoon. Welcome in. Something specific in mind, or just browsing?",
    "Hello. Are you looking at ideas, checking if we cover your area, or after pricing?"
  ],
  evening: [
    "Good evening. Welcome to Summit. What brought you in tonight?",
    "Evening — glad you're here. Tell us what you're working on.",
    "Good evening. How can we help — designs, materials, or coverage?"
  ],
  neutral: [
    "Welcome to Summit. What are you working on?",
    "Hi there — we'd love to help. Where would you like to start?"
  ]
} as const;

// The NEX reply is generated by the local NEX conversation pipeline
// (ADR-0044 · POST /api/nex-conv/chat → processTurn → local Qwen).
// No canned line is used in the normal flow. If the very first call fails
// (server booting, Ollama not running, etc.) the customer sees the fallback
// once and can retry.
const NEX_ERROR_FALLBACK = "Give me a moment — the assistant is still starting up. Please send that again in a few seconds.";

const COMPOSER_PLACEHOLDERS = [
  "Ask Summit anything about your staircase…",
  "Try: how much for a floating oak staircase?",
  "Try: do you install in my area?",
  "Try: can I see examples of your work?",
  "Try: how long does a project take?"
];

export function STCH01(props: Config = {}) {
  const c = { ...DEFAULTS, ...props };
  const [messages, setMessages] = useState<Msg[]>(c.initialConversation);
  const [input, setInput] = useState("");
  const [thinking, setThinking] = useState<Agent | null>(null);
  const [customerHasSpoken, setCustomerHasSpoken] = useState(false);
  const [placeholderIdx, setPlaceholderIdx] = useState(0);
  const streamRef = useRef<HTMLDivElement | null>(null);

  const isEmpty = messages.length === 0 && thinking === null;

  /* ── Auto-greeting on mount ─────────────────────────────────────
   * 700ms of Summit "typing" · then the greeting bubble slides in. */
  useEffect(() => {
    if (c.skipGreeting || c.initialConversation.length > 0) return;
    const greeting = pickGreeting();
    setThinking("summit");
    const timer = window.setTimeout(() => {
      setThinking(null);
      setMessages([{ agent: "summit", text: greeting }]);
    }, 900);
    return () => window.clearTimeout(timer);
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, []);

  /* ── Placeholder morph · cycles the composer hint every 4s ───── */
  useEffect(() => {
    if (input.length > 0) return;
    const t = window.setInterval(() => {
      setPlaceholderIdx((i) => (i + 1) % COMPOSER_PLACEHOLDERS.length);
    }, 4000);
    return () => window.clearInterval(t);
  }, [input]);

  // Per-browser conversation id · one-shot on mount · persisted in
  // localStorage so a page reload resumes the same conversation state
  // that Postgres has for it.
  const conversationIdRef = useRef<string | null>(null);
  useEffect(() => {
    if (typeof window === "undefined") return;
    const KEY = "nex-conv-id-mt1";
    let id = window.localStorage.getItem(KEY);
    if (!id) {
      id = (window.crypto?.randomUUID?.() ?? `mt1-${Math.random().toString(36).slice(2)}-${Date.now().toString(36)}`);
      window.localStorage.setItem(KEY, id);
    }
    conversationIdRef.current = id;
    // Fire-and-forget warmup so the customer's first real message doesn't
    // wait through store-init + Ollama cold-load (~15-30s).
    fetch("/api/nex-conv/chat", { method: "GET" }).catch(() => { /* silent */ });
  }, []);

  const send = useCallback(async (raw: string) => {
    const text = raw.trim();
    if (!text) return;
    setInput("");
    setMessages((m) => [...m, { agent: "customer", text }]);
    if (!customerHasSpoken) setCustomerHasSpoken(true);

    // NEX is the one actually responding · routed via the local NEX
    // conversation pipeline (ADR-0044). Summit stays quiet until we
    // wire her separately (out-of-hours handoff etc). Zero canned
    // replies · zero third-party AI · everything through local Qwen.
    setThinking("nex");
    try {
      const resp = await fetch("/api/nex-conv/chat", {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({
          conversation_id: conversationIdRef.current,
          message: text,
        }),
      });
      const j = (await resp.json().catch(() => null)) as { reply?: string; conversation_id?: string; error?: string } | null;
      if (!resp.ok) {
        const errMsg = j?.error ? `Hmm — ${j.error}` : NEX_ERROR_FALLBACK;
        setMessages((m) => [...m, { agent: "nex", text: errMsg }]);
      } else if (!j?.reply) {
        setMessages((m) => [...m, { agent: "nex", text: NEX_ERROR_FALLBACK }]);
      } else {
        setMessages((m) => [...m, { agent: "nex", text: j.reply as string }]);
        if (typeof j.conversation_id === "string") {
          conversationIdRef.current = j.conversation_id;
        }
      }
    } catch (e) {
      const message = e instanceof Error ? e.message : String(e);
      setMessages((m) => [...m, { agent: "nex", text: `${NEX_ERROR_FALLBACK} (${message.slice(0, 80)})` }]);
    } finally {
      setThinking(null);
    }
  }, [customerHasSpoken]);

  useEffect(() => {
    const el = streamRef.current;
    if (!el) return;
    el.scrollTo({ top: el.scrollHeight, behavior: "smooth" });
  }, [messages, thinking]);

  const onSubmit = useCallback((e: React.FormEvent) => {
    e.preventDefault();
    send(input);
  }, [send, input]);

  const rotatedPlaceholder = COMPOSER_PLACEHOLDERS[placeholderIdx];

  return (
    <div
      data-section-id="ST-CH01"
      data-master-template="1"
      data-vertical="staircase"
      data-family="premium-architectural"
      style={{
        position: "relative",
        minHeight: "100dvh",
        // Wallpaper set on the container · owner-swappable later via
        // NEX Assist ("change my chat wallpaper"). Cream fallback under
        // the image in case it fails to load.
        background: `${T.color.surface} url(${c.chatBackgroundUrl}) center/cover fixed no-repeat`,
        color: T.color.ink,
        fontFamily: T.font.sans,
        display: "flex",
        flexDirection: "column"
      }}
    >
      <FloatingHeader c={c} />

      <div
        ref={streamRef}
        style={{
          flex: 1,
          overflowY: "auto",
          scrollBehavior: "smooth",
          padding: "112px clamp(16px, 4vw, 40px) 24px",
          display: "flex",
          flexDirection: "column"
        }}
      >
        <div style={{ maxWidth: 760, width: "100%", margin: "0 auto", flex: 1, display: "flex", flexDirection: "column" }}>
          {isEmpty && messages.length === 0 && (
            <EmptyState c={c} onPrompt={send} />
          )}

          {messages.length > 0 && (
            <div style={{ display: "flex", flexDirection: "column", gap: 14 }}>
              {messages.map((m, i) => (
                <MessageBubble
                  key={i}
                  msg={m}
                  brandInitial={c.brandInitial}
                  index={i}
                />
              ))}
            </div>
          )}

          {thinking && (
            <div style={{ marginTop: messages.length > 0 ? 14 : 0 }}>
              <ThinkingBubble
                agent={thinking}
                brandInitial={c.brandInitial}
              />
            </div>
          )}
        </div>
      </div>

      <Composer
        value={input}
        onChange={setInput}
        onSubmit={onSubmit}
        placeholder={rotatedPlaceholder}
      />

      {/* Global animations · used by bubbles + presence pulse */}
      <style>{`
        @keyframes mt1-msg-in {
          from { opacity: 0; transform: translateY(8px) scale(0.98); }
          to   { opacity: 1; transform: translateY(0)   scale(1); }
        }
        @keyframes mt1-presence-pulse {
          0%, 100% { box-shadow: 0 0 0 0   rgba(76, 179, 125, 0.55); }
          70%      { box-shadow: 0 0 0 8px rgba(76, 179, 125, 0);    }
        }
        @keyframes mt1-think-bob {
          0%, 80%, 100% { transform: translateY(0);  opacity: 0.35; }
          40%           { transform: translateY(-4px); opacity: 1; }
        }
        @keyframes mt1-placeholder-fade {
          0%   { opacity: 0; transform: translateY(4px); }
          100% { opacity: 1; transform: translateY(0); }
        }
        .mt1-bubble-in { animation: mt1-msg-in 320ms cubic-bezier(0.22, 1, 0.36, 1) both; }
        .mt1-presence  { animation: mt1-presence-pulse 2.6s ease-out infinite; }
        @media (prefers-reduced-motion: reduce) {
          .mt1-bubble-in, .mt1-presence { animation: none !important; }
        }
        /* Hide the Next.js dev-tools indicator (yellow burger top-right)
           on the chat surface · Philip 2026-08-15. Dev-only artefact,
           never shipped to customers anyway. */
        nextjs-portal,
        [data-nextjs-toast],
        [data-nextjs-dialog-overlay],
        #__next-build-watcher,
        #vercel-live-feedback { display: none !important; }
      `}</style>
    </div>
  );
}

