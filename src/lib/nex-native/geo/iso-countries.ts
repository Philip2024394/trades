/** Pure · lookup by alpha-2 code (uppercase). O(n) over 249 entries,
 *  which is cheap enough to avoid a Map and keep the module tree-shakable. */
export function findIsoCountry(alpha2: string): IsoCountry | null {
  const key = alpha2.toUpperCase();
  for (const c of ISO_COUNTRIES) if (c.isoAlpha2 === key) return c;
  return null;
}

/** Pure · UK is a documented GB mis-mapping trap. UK is NOT ISO 3166-1
 *  alpha-2 for the United Kingdom (it is "GB"); UK is reserved to the
 *  United Nations and not assigned to a country. This helper rejects
 *  "UK" explicitly so a mistaken input returns null rather than
 *  silently matching nothing. */
export function parseIsoAlpha2(input: string | null | undefined): string | null {
  if (!input) return null;
  const up = input.toUpperCase();
  if (up === "UK") return null; // trap · caller must use "GB"
  if (!/^[A-Z]{2}$/.test(up)) return null;
  return findIsoCountry(up) ? up : null;
}
