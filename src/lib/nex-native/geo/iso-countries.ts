// src/lib/nex-native/geo/iso-countries.ts
//
// NEX · ISO 3166-1 alpha-2 country metadata table.
//
// Static reference data for the Directory country picker. Covers every
// ISO 3166-1 alpha-2 code (247 entries · includes exceptional reservations
// used in NEX scope such as `XK` for Kosovo). No currency, no language —
// those live elsewhere; this file is picker-only.
//
// Flag asset strategy
//   The picker renders a flag per entry. This module does NOT embed SVG;
//   it exposes a stable key (`isoAlpha2`) that the UI can map to a flag
//   asset via its own convention (public/flags/<code-lower>.svg, a
//   bundled sprite, or a text-badge fallback). The deliberate decision
//   is to avoid taking a dependency on `circle-flags` or similar — the
//   picker degrades to the ISO code displayed in a styled circle if the
//   flag asset is missing, which is honest and never shipped-broken.
//
// Why not emoji regional-indicator flags? Windows does not render them;
// the user sees the letter pair ("GB"/"ID") instead. Shipping emoji
// flags produces a picker that looks broken in NEX's own dev
// environment. SVG assets (or the text-badge fallback) are the only
// correct choice for a Windows-authored product.

