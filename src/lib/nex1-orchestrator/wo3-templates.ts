// -- Plain Node HTTP server (used by WO-11 for the first-app acceptance
//    test). Deliberately zero-dependency so real build+runtime finish in
//    seconds instead of the 10 min a full `npm install`+`next build` needs.
//    Routes are configurable; each path returns its `body` verbatim with
//    200; every other path returns 404. The server reads its port from
//    the env var named by port_env_var (default PORT). Exits cleanly on
//    SIGTERM so WO-06 termination protocol works. -----------------

const plainNodeServerParams = z.object({
  port_env_var: z.string().min(1).default("PORT"),
  default_port: z.number().int().min(1).max(65_535).default(3000),
  routes: z.array(z.object({
    path: z.string().refine((s) => s.startsWith("/"), "route path must start with /"),
    body: z.string(),
  })).min(1),
});

export const PLAIN_NODE_SERVER_TEMPLATE: TemplateDefinition<z.infer<typeof plainNodeServerParams>> = {
  template_ref: "plain-node-server.v1",
  description: "Zero-dependency Node HTTP server with configurable routes; used for WO-11 first-app acceptance",
  paramsSchema: plainNodeServerParams,
  file_extension: "js",
  render: (p) => {
    const routesLiteral = p.routes
      .map((r) => `  ${JSON.stringify(r.path)}: ${JSON.stringify(r.body)}`)
      .join(",\n");
    return (
      `// Auto-generated by NEX1 WO-11 · plain Node HTTP server\n` +
      `const http = require('http');\n` +
      `const port = Number(process.env.${p.port_env_var} || ${p.default_port});\n` +
      `const routes = {\n${routesLiteral}\n};\n` +
      `const server = http.createServer((req, res) => {\n` +
      `  const key = req.url;\n` +
      `  if (Object.prototype.hasOwnProperty.call(routes, key)) {\n` +
      `    res.writeHead(200, { 'content-type': 'text/plain; charset=utf-8' });\n` +
      `    res.end(routes[key]);\n` +
      `  } else {\n` +
      `    res.writeHead(404, { 'content-type': 'text/plain; charset=utf-8' });\n` +
      `    res.end('Not Found');\n` +
      `  }\n` +
      `});\n` +
      `server.listen(port, '127.0.0.1', () => { console.log('listening on ' + port); });\n` +
      `process.on('SIGTERM', () => { server.close(() => process.exit(0)); });\n`
    );
  },
};

// ── Registry ────────────────────────────────────────────────────────────

const TEMPLATE_LIST: readonly TemplateDefinition<unknown>[] = [
  NEXT_APP_PAGE_TEMPLATE as TemplateDefinition<unknown>,
  NEXT_ROOT_LAYOUT_TEMPLATE as TemplateDefinition<unknown>,
  PACKAGE_JSON_TEMPLATE as TemplateDefinition<unknown>,
  README_TEMPLATE as TemplateDefinition<unknown>,
  PLAIN_TEXT_TEMPLATE as TemplateDefinition<unknown>,
  PLAIN_NODE_SERVER_TEMPLATE as TemplateDefinition<unknown>,
];

const TEMPLATE_MAP: ReadonlyMap<string, TemplateDefinition<unknown>> = new Map(
  TEMPLATE_LIST.map((t) => [t.template_ref, t] as const),
);

/** Look up a template by ref. Returns undefined if not registered — the
 *  generator surfaces this as a specific TEMPLATE_UNKNOWN failure. */
export function findTemplate(template_ref: string): TemplateDefinition<unknown> | undefined {
  return TEMPLATE_MAP.get(template_ref);
}

/** Sorted list of registered template refs. Useful for error messages
 *  ("did you mean …?") and telemetry. */
export function listTemplateRefs(): readonly string[] {
  return TEMPLATE_LIST.map((t) => t.template_ref).slice().sort();
}
