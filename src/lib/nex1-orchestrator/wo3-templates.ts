// WO-WORKSTATION-03 · template registry
//
// Founder-authorised 2026-09-13 per ADR-0319 Workstation Activation Programme.
// Deterministic code-authoring templates. Templates are TypeScript functions
// that return strings — no external templating engine, no {{}} substitution
// magic, no LLM anywhere in the pipeline (P-S). Every template's output is
// a pure function of its typed params — same input, same bytes.
//
// The first slice of WO-03 provides a small but real template set: enough
// to author a plain Next.js App Router page (page.tsx), a simple JSON
// config, a package.json manifest, and a plain text README. That's
// sufficient for the 3-page-app acceptance test WO-11 will build toward.

import { z } from "zod";

// ── Template contract ───────────────────────────────────────────────────

export interface TemplateDefinition<TParams = unknown> {
  readonly template_ref: string;
  readonly description: string;
  /** Zod validator for the params object. Rejected params -> generator
   *  fails with a specific error before content is ever produced. */
  readonly paramsSchema: z.ZodType<TParams>;
  readonly render: (params: TParams) => string;
  /** File extension the template produces. Used by the syntax validator
   *  to pick the right check. */
  readonly file_extension: "tsx" | "ts" | "json" | "md" | "css" | "txt";
}

// ── Deterministic string escaping helpers ───────────────────────────────

/** Escape backslashes, quotes, and newlines for embedding in a TS string
 *  literal wrapped by double quotes. Deterministic. */
export function escapeForDoubleQuoted(s: string): string {
  return s
    .replace(/\\/g, "\\\\")
    .replace(/"/g, '\\"')
    .replace(/\n/g, "\\n")
    .replace(/\r/g, "\\r")
    .replace(/\t/g, "\\t");
}

/** Escape for use inside a JSX text node. Turns `<`, `>`, `&`, `{`, `}`
 *  into safe sequences. */
export function escapeForJsxText(s: string): string {
  return s
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/\{/g, "&#123;")
    .replace(/\}/g, "&#125;");
}

// ── Templates ───────────────────────────────────────────────────────────

// -- Next.js App Router page.tsx (server component, no client bailouts) --

const nextAppPageParams = z.object({
  route: z.string().min(1),                // used only in comment
  title: z.string().min(1),
  headline: z.string().min(1),
  paragraphs: z.array(z.string().min(1)).min(1),
});

export const NEXT_APP_PAGE_TEMPLATE: TemplateDefinition<z.infer<typeof nextAppPageParams>> = {
  template_ref: "next-app-page.v1",
  description: "Next.js 15/16 App Router page.tsx — server component, no hooks, no useSearchParams (so no Suspense wrap needed)",
  paramsSchema: nextAppPageParams,
  file_extension: "tsx",
  render: (p) => {
    const paragraphs = p.paragraphs
      .map((para) => `      <p>${escapeForJsxText(para)}</p>`)
      .join("\n");
    return (
      `// Auto-generated by NEX1 WO-03 · route ${p.route}\n` +
      `import type { Metadata } from "next";\n` +
      `\n` +
      `export const metadata: Metadata = {\n` +
      `  title: "${escapeForDoubleQuoted(p.title)}"\n` +
      `};\n` +
      `\n` +
      `export default function Page() {\n` +
      `  return (\n` +
      `    <main>\n` +
      `      <h1>${escapeForJsxText(p.headline)}</h1>\n` +
      `${paragraphs}\n` +
      `    </main>\n` +
      `  );\n` +
      `}\n`
    );
  },
};

