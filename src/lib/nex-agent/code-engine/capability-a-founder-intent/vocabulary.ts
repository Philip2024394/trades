/**
 * Unified coding-lexeme index. lexeme → category. Enforces disjointness across
 * tool / framework / concept / language AND against the verb-lexeme index.
 * Fail-loud on any conflict at module load.
 */
export const CODING_LEXEME_INDEX: ReadonlyMap<string, Nex1CodingCategory> = (() => {
  const map = new Map<string, Nex1CodingCategory>();
  const sources: readonly ReadonlyMap<string, Nex1CodingCategory>[] = [
    TOOL_LEXEMES,
    FRAMEWORK_LEXEMES,
    CODE_CONCEPT_LEXEMES,
    LANGUAGE_LEXEMES,
  ];
  for (const src of sources) {
    for (const [lex, cat] of src) {
      if (map.has(lex)) {
        throw new Error(
          `capability-a vocabulary invariant broken: coding lexeme '${lex}' claimed by both '${map.get(lex)}' and '${cat}'`,
        );
      }
      if (VERB_LEXEME_INDEX.has(lex)) {
        throw new Error(
          `capability-a vocabulary invariant broken: lexeme '${lex}' is already a verb (family=${VERB_LEXEME_INDEX.get(lex)}) · cannot also be a coding lexeme`,
        );
      }
      map.set(lex, cat);
    }
  }
  return map;
})();
