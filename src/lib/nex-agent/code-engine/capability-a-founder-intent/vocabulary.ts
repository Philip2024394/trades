/**
 * All whole-token verb lexemes indexed by lexeme → family for O(1) lookup.
 * Frozen. Computed at module load; static thereafter.
 */
export const VERB_LEXEME_INDEX: ReadonlyMap<string, Nex1VerbFamily> = (() => {
  const map = new Map<string, Nex1VerbFamily>();
  const families = Object.keys(VERB_FAMILY_VARIANTS) as Nex1VerbFamily[];
  for (const family of families) {
    for (const variant of VERB_FAMILY_VARIANTS[family]) {
      if (map.has(variant)) {
        // Fail-loud during module load if a lexeme is claimed by two families.
        throw new Error(
          `capability-a vocabulary invariant broken: lexeme '${variant}' claimed by both '${map.get(variant)}' and '${family}'`,
        );
      }
      map.set(variant, family);
    }
  }
  return map;
})();

/** Deliverable phrase-list flattened for scanner iteration (longer phrases first). */
export const DELIVERABLE_SCAN_ORDER: readonly { readonly phrase: string; readonly kind: Nex1DeliverableKind }[] =
  (() => {
    const out: { phrase: string; kind: Nex1DeliverableKind }[] = [];
    const kinds = Object.keys(DELIVERABLE_PHRASES) as Nex1DeliverableKind[];
    for (const k of kinds) {
      for (const phrase of DELIVERABLE_PHRASES[k]) {
        out.push({ phrase, kind: k });
      }
    }
    out.sort((a, b) => b.phrase.length - a.phrase.length);
    return Object.freeze(out);
  })();

