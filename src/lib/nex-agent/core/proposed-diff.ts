// NEX Agent v1.1 · Proposed-diff preview generator.
// nex1 composes realistic template content for each planned file so the founder
// can PREVIEW the code before approving. Nothing is written to disk in V1.1 —
// the preview is a courtesy so the founder can spot problems before the engineer
// starts building.
//
// Templates are deterministic. No LLM. Content includes the CLAUDE.md-mandated
// leading `//` summary comment, the ADR-compliant defaults, and TODO markers
// where the engineer must decide details.

import type { Plan, ProposedFile, Intent } from "./orchestrator-types";

const TS_TIMESTAMP = new Date().toISOString().slice(0, 10);

function tsHeader(path: string, oneLineSummary: string): string {
  return `// ${path}
//
// ${oneLineSummary}
// Generated by NEX Agent v1.1 · ${TS_TIMESTAMP}
`;
}

